/**
 * Parte do modelo que pertence ao customers: clientes e veículos da "Freios Rodovia Ltda". O modelo anterior some
 * junto com a empresa (cascata), então aqui só se insere.
 */
export async function seedCustomersTemplate(db: Db, companyId: string) {
	const created = await db
		.insert(customers)
		.values(
			data.map(([kind, name, base, city, phone, creditLimit, status]) => ({
				companyId,
				kind,
				name,
				document: withCheckDigits(base),
				phone,
				city,
				state: "SP",
				creditLimit: creditLimit.toFixed(2),
				status,
			})),
		)
		.returning({ id: customers.id, document: customers.document });
	const idByDocument = new Map(created.map((c) => [c.document, c.id]));

	await db.insert(vehicles).values(
		data.flatMap(([, , base, , , , , fleet]) =>
			fleet.map(([plate, model, axles, year]) => ({
				companyId,
				customerId: idByDocument.get(withCheckDigits(base)) as string,
				plate,
				model,
				axles,
				year,
			})),
		),
	);
	return { customers: created.length };
}
